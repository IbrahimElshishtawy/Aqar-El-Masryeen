// 3. WIDGET TRANSPILER
// ========================
function transpileWidget(dartCode: string, componentsFound: string[], filePath: string): string {
  const widgetRegex = /class\s+([A-Za-z0-9_]+)\s+extends\s+(StatelessWidget|StatefulWidget|ConsumerWidget)/g;
  let match = widgetRegex.exec(dartCode);

  const componentName = match ? match[1] : toPascalCase(filePath.replace('.dart', '').split('/').pop() || 'Widget');
  componentsFound.push(componentName);

  // Extract constructor parameters / props
  const props = extractWidgetProps(dartCode);

  // Analyze widget contents for icons, labels, colors, layouts
  const icons = extractIcons(dartCode);
  const labels = extractArabicStrings(dartCode);

  let iconImports = '';
  if (icons.length > 0) {
    iconImports = `import { ${Array.from(new Set(icons)).join(', ')} } from 'lucide-react';\n`;
  }

  let propsInterface = '';
  if (props.length > 0) {
    propsInterface = `export interface ${componentName}Props {\n`;
    for (const p of props) {
      propsInterface += `  ${p.name}${p.optional ? '?' : ''}: ${p.type};\n`;
    }
    propsInterface += `  className?: string;\n`;
    propsInterface += `}\n\n`;
  }

  const propArgs = props.length > 0
    ? `{ ${props.map(p => p.name).join(', ')}${props.length ? ', ' : ''}className = '' }: ${componentName}Props`
    : `{ className = '' }: { className?: string }`;

  // Generate JSX body based on specific widget types
  let jsxBody = generateTailwindJsx(dartCode, componentName, props, icons, labels);

  return `'use client';

import React from 'react';
${iconImports}
${propsInterface}export function ${componentName}(${propArgs}) {
  return (
${jsxBody}
  );
}

export default ${componentName};
`;
}

