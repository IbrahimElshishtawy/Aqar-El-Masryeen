// Transpiler Engine: Flutter/Dart to Next.js (React TSX + Tailwind CSS)
// Specifically tuned for Aqar El Masryeen and general Flutter lib structures

export interface TranspileResult {
  originalCode: string;
  convertedCode: string;
  targetPath: string;
  fileType: 'model' | 'enum' | 'widget' | 'screen' | 'service' | 'config' | 'util';
  stats: {
    originalLines: number;
    convertedLines: number;
    componentsFound: string[];
    modelsFound: string[];
    enumsFound: string[];
  };
}

export function determineTargetFilePath(dartPath: string): { targetPath: string; fileType: TranspileResult['fileType'] } {
  // Normalize path
  const normalized = dartPath.replace(/\\/g, '/');
  const fileName = normalized.split('/').pop() || 'unknown.dart';
  const baseName = fileName.replace('.dart', '');

  if (normalized.includes('/enums/') || baseName.endsWith('_enums') || baseName === 'app_enums') {
    return { targetPath: `src/types/${toKebabCase(baseName)}.ts`, fileType: 'enum' };
  }

  if (normalized.includes('/models/') || baseName.endsWith('_model') || baseName.endsWith('_models')) {
    return { targetPath: `src/types/${toKebabCase(baseName)}.ts`, fileType: 'model' };
  }

  if (normalized.includes('/presentation/') && baseName.endsWith('_screen')) {
    const routeName = baseName.replace('_screen', '');
    return { targetPath: `src/app/${toKebabCase(routeName)}/page.tsx`, fileType: 'screen' };
  }

  if (normalized.includes('/widgets/') || normalized.includes('/core/widgets/')) {
    const compName = toPascalCase(baseName);
    return { targetPath: `src/components/${compName}.tsx`, fileType: 'widget' };
  }

  if (normalized.includes('/domain/') || normalized.includes('/data/') || baseName.endsWith('_repository') || baseName.endsWith('_calculator')) {
    return { targetPath: `src/services/${toKebabCase(baseName)}.ts`, fileType: 'service' };
  }

  if (normalized.includes('/routing/') || baseName.includes('routes') || baseName.includes('router')) {
    return { targetPath: `src/lib/routes.ts`, fileType: 'config' };
  }

  if (normalized.includes('/utils/') || normalized.includes('/constants/')) {
    return { targetPath: `src/lib/${toKebabCase(baseName)}.ts`, fileType: 'util' };
  }

  // Fallback
  return { targetPath: `src/converted/${toKebabCase(baseName)}.tsx`, fileType: 'widget' };
}

export function transpileDartToNextJs(dartCode: string, filePath = 'unknown.dart'): TranspileResult {
  const { targetPath, fileType } = determineTargetFilePath(filePath);
  const originalLines = dartCode.split('\n').length;

  let convertedCode = '';
  const componentsFound: string[] = [];
  const modelsFound: string[] = [];
  const enumsFound: string[] = [];

  switch (fileType) {
    case 'enum':
      convertedCode = transpileEnums(dartCode, enumsFound);
      break;
    case 'model':
      convertedCode = transpileModels(dartCode, modelsFound);
      break;
    case 'widget':
      convertedCode = transpileWidget(dartCode, componentsFound, filePath);
      break;
    case 'screen':
      convertedCode = transpileScreen(dartCode, componentsFound, filePath);
      break;
    case 'service':
      convertedCode = transpileService(dartCode);
      break;
    case 'config':
    case 'util':
    default:
      convertedCode = transpileGenericDart(dartCode);
      break;
  }

  const convertedLines = convertedCode.split('\n').length;

  return {
    originalCode: dartCode,
    convertedCode,
    targetPath,
    fileType,
    stats: {
      originalLines,
      convertedLines,
      componentsFound,
      modelsFound,
      enumsFound,
    },
  };
}

// ========================
// 1. ENUMS TRANSPILER
// ========================
function transpileEnums(dartCode: string, enumsFound: string[]): string {
  const enumRegex = /enum\s+([A-Za-z0-9_]+)\s*\{([^}]+)\}/g;
  const extensionRegex = /extension\s+([A-Za-z0-9_]+)\s+on\s+([A-Za-z0-9_]+)\s*\{([\s\S]*?)\}/g;

  // Extract label map from extension if present
  const labelMaps: Record<string, Record<string, string>> = {};
  const caseRegex = /case\s+([A-Za-z0-9_]+)\.([A-Za-z0-9_]+):\s*(?:return\s+['"]([^'"]+)['"];)/g;
  let extMatch;
  while ((extMatch = caseRegex.exec(dartCode)) !== null) {
    const enumName = extMatch[1];
    const enumVal = extMatch[2];
    const label = extMatch[3];
    if (!labelMaps[enumName]) labelMaps[enumName] = {};
    labelMaps[enumName][enumVal] = label;
  }

  let output = `// Auto-converted from Flutter / Dart Enums
// Generated by Aqar El Masryeen Next.js Transpiler

`;

  let match;
  while ((match = enumRegex.exec(dartCode)) !== null) {
    const name = match[1];
    enumsFound.push(name);
    const rawValues = match[2]
      .split(',')
      .map(v => v.trim())
      .filter(v => v && !v.startsWith('//'));

    output += `export enum ${name} {\n`;
    for (const val of rawValues) {
      const cleanVal = val.replace(/;/, '').trim();
      const pascal = toPascalCase(cleanVal);
      output += `  ${pascal} = '${cleanVal}',\n`;
    }
    output += `}\n\n`;

    // Also output Arabic label dictionary
    output += `export const ${name}Labels: Record<${name}, string> = {\n`;
    for (const val of rawValues) {
      const cleanVal = val.replace(/;/, '').trim();
      const pascal = toPascalCase(cleanVal);
      const arabicLabel = labelMaps[name]?.[cleanVal] || cleanVal;
      output += `  [${name}.${pascal}]: '${arabicLabel}',\n`;
    }
    output += `};\n\n`;
  }

  if (enumsFound.length === 0) {
    return transpileGenericDart(dartCode);
  }

  return output;
}

// ========================
// 2. MODELS TRANSPILER
// ========================
function transpileModels(dartCode: string, modelsFound: string[]): string {
  let output = `// Auto-converted from Flutter Models to TypeScript Interfaces
// Generated by Aqar El Masryeen Next.js Transpiler

`;

  // Find classes
  const classRegex = /class\s+([A-Za-z0-9_]+)(?:\s+extends\s+[A-Za-z0-9_]+)?\s*\{([\s\S]*?)\n\}/g;
  let classMatch;

  while ((classMatch = classRegex.exec(dartCode)) !== null) {
    const className = classMatch[1];
    const classBody = classMatch[2];
    modelsFound.push(className);

    // Extract fields: final Type name; or Type? name;
    const fieldRegex = /(?:final\s+)?([A-Za-z0-9_<>?]+)\s+([A-Za-z0-9_]+);/g;
    let fieldMatch;
    const fields: { name: string; type: string; optional: boolean }[] = [];

    while ((fieldMatch = fieldRegex.exec(classBody)) !== null) {
      const rawType = fieldMatch[1];
      const fieldName = fieldMatch[2];

      if (fieldName.startsWith('_')) continue; // Skip private fields like _apartmentCount

      const isOptional = rawType.endsWith('?');
      const cleanType = rawType.replace('?', '');
      const tsType = mapDartTypeToTs(cleanType);

      fields.push({
        name: fieldName,
        type: tsType,
        optional: isOptional,
      });
    }

    output += `export interface ${className} {\n`;
    for (const f of fields) {
      output += `  ${f.name}${f.optional ? '?' : ''}: ${f.type};\n`;
    }
    output += `}\n\n`;

    // Default factory / constructor
    output += `export function createDefault${className}(): ${className} {\n`;
    output += `  return {\n`;
    for (const f of fields) {
      output += `    ${f.name}: ${getDefaultValueForType(f.type, f.optional)},\n`;
    }
    output += `  };\n`;
    output += `}\n\n`;
  }

  if (modelsFound.length === 0) {
    return transpileGenericDart(dartCode);
  }

  return output;
}

